package com.example.movie;

import com.example.movie.dto.*;
import com.example.movie.model.*;
import com.example.movie.repository.*;
import com.example.movie.service.*;
import jakarta.validation.ConstraintViolationException;
import org.junit.jupiter.api.*;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.test.context.ActiveProfiles;
import org.springframework.security.test.context.support.WithMockUser;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.dao.DataIntegrityViolationException;
import org.springframework.transaction.PlatformTransactionManager;
import org.springframework.transaction.support.TransactionTemplate;
import java.time.*;
import java.math.BigDecimal;
import static org.assertj.core.api.Assertions.*;

@SpringBootTest(properties="spring.datasource.url=jdbc:h2:mem:person3_prices;MODE=MySQL;DB_CLOSE_DELAY=-1")
@ActiveProfiles("test") @WithMockUser(roles="ADMIN")
class ShowtimePriceIntegrationTest {
 @Autowired ShowtimeService schedules; @Autowired TheaterService theaters; @Autowired RoomService rooms;
 @Autowired MovieRepository movies; @Autowired ShowtimeRepository repository; @Autowired RoomRepository roomRepository; @Autowired TheaterRepository theaterRepository;
 @Autowired JdbcTemplate jdbc; @Autowired PlatformTransactionManager txManager;
 Long movieId,roomId;LocalDateTime start;
 @BeforeEach void setup(){
  var theater=theaters.create(new TheaterForm("Rạp giá","Địa chỉ",true));roomId=rooms.create(new RoomForm(theater.getId(),"A",RoomType.TWO_D,true)).getId();
  start=LocalDate.now(Movie.CINEMA_ZONE).plusDays(20).atTime(10,0);
  var movie=new Movie();movie.setTitle("Phim giá");movie.setDirector("Đạo diễn");movie.setDurationMinutes(90);movie.setReleaseDate(start.toLocalDate().minusDays(1));movie.setAgeRating(AgeRating.P);movie.setSynopsis("Nội dung");movie.setVisible(true);movieId=movies.saveAndFlush(movie).getId();
  // A historical price snapshot fixture, not an implementation of Member 4's Booking.
  jdbc.execute("create table if not exists price_history_fixture(id bigint generated by default as identity primary key, showtime_id bigint not null references showtimes(id), price_at_booking decimal(12,2) not null)");
 }
 @AfterEach void cleanup(){jdbc.update("delete from price_history_fixture");repository.deleteAll();roomRepository.deleteAll();theaterRepository.deleteAll();movies.deleteAll();}
 ShowtimeForm form(String normal,String vip){return new ShowtimeForm(movieId,roomId,start,normal==null?null:new BigDecimal(normal),vip==null?null:new BigDecimal(vip),ShowtimeStatus.OPEN);}
 ShowtimeSummary create(){return schedules.create(form("80000","100000"));}
 @Test void createsBothPricesAndReloadsExactDecimalValues(){
  var s=schedules.create(form("80000.25","110000.75"));var loaded=schedules.getForAdmin(s.id());
  assertThat(loaded.normalPrice()).isEqualByComparingTo("80000.25");assertThat(loaded.vipPrice()).isEqualByComparingTo("110000.75");
  assertThat(schedules.getBookableShowtime(s.id()).normalPrice()).isEqualByComparingTo("80000.25");
 }
 @Test void normalPriceCanChangeIndependentlyAndLegacyColumnRemainsUnchanged(){
  var s=create();var changed=schedules.update(s.id(),form("85000","100000"));
  assertThat(changed.id()).isEqualTo(s.id());assertThat(changed.normalPrice()).isEqualByComparingTo("85000");assertThat(changed.vipPrice()).isEqualByComparingTo("100000");
  assertThat(changed.basePrice()).isEqualByComparingTo("80000");
 }
 @Test void vipPriceCanChangeIndependently(){
  var s=create();var changed=schedules.update(s.id(),form("80000","125000"));assertThat(changed.normalPrice()).isEqualByComparingTo("80000");assertThat(changed.vipPrice()).isEqualByComparingTo("125000");
 }
 @Test void vipMayBeCheaperThanNormal(){var s=schedules.create(form("90000","50000"));assertThat(s.vipPrice()).isEqualByComparingTo("50000");}
 @Test void sameMovieSchedulesHaveIndependentPrices(){
  var first=create();var second=schedules.create(new ShowtimeForm(movieId,roomId,start.plusHours(2),new BigDecimal("60000"),new BigDecimal("70000"),ShowtimeStatus.OPEN));
  assertThat(schedules.getForAdmin(first.id()).normalPrice()).isEqualByComparingTo("80000");assertThat(schedules.getForAdmin(second.id()).normalPrice()).isEqualByComparingTo("60000");
 }
 @Test void eitherMissingPriceRejected(){
  assertThatThrownBy(()->schedules.create(form(null,"100000"))).isInstanceOf(ConstraintViolationException.class);
  assertThatThrownBy(()->schedules.create(form("80000",null))).isInstanceOf(ConstraintViolationException.class);assertThat(repository.count()).isZero();
 }
 @Test void zeroAndNegativePricesRejectedForEitherType(){
  for(String price:new String[]{"0","-1"}){
   assertThatThrownBy(()->schedules.create(form(price,"100000"))).isInstanceOf(ConstraintViolationException.class);
   assertThatThrownBy(()->schedules.create(form("80000",price))).isInstanceOf(ConstraintViolationException.class);
  }assertThat(repository.count()).isZero();
 }
 @Test void excessiveScaleAndPrecisionRejectedWithoutRounding(){
  for(String price:new String[]{"0.001","10000000000"}){
   assertThatThrownBy(()->schedules.create(form(price,"100000"))).isInstanceOf(ConstraintViolationException.class);
   assertThatThrownBy(()->schedules.create(form("80000",price))).isInstanceOf(ConstraintViolationException.class);
  }
 }
 @Test void entitySelectsConfiguredPriceWithoutAnyVipSurcharge(){
  var s=create();var entity=repository.findById(s.id()).orElseThrow();
  assertThat(entity.priceFor(SeatType.NORMAL)).isEqualByComparingTo("80000");assertThat(entity.priceFor(SeatType.VIP)).isEqualByComparingTo("100000");
  assertThatThrownBy(()->entity.priceFor(SeatType.COUPLE)).isInstanceOf(IllegalArgumentException.class);
 }
 Showtime legacy(){
  var s=new Showtime();s.setMovie(movies.findById(movieId).orElseThrow());s.setRoom(roomRepository.findById(roomId).orElseThrow());s.setStartTime(start);s.setEndTime(start.plusMinutes(90));s.setBasePrice(new BigDecimal("75000"));s.setStatus(ShowtimeStatus.OPEN);return repository.saveAndFlush(s);
 }
 @Test void legacyRowsRemainReadableButNotBookableUntilBothPricesAreChosen(){
  var old=legacy();var loaded=schedules.getForAdmin(old.getId());assertThat(loaded.id()).isEqualTo(old.getId());assertThat(loaded.basePrice()).isEqualByComparingTo("75000");assertThat(loaded.normalPrice()).isNull();assertThat(loaded.vipPrice()).isNull();
  assertThat(schedules.findOpenShowtimes(movieId,null,start.toLocalDate())).isEmpty();
  assertThatThrownBy(()->schedules.getBookableShowtime(old.getId())).isInstanceOf(ScheduleValidationException.class);
  assertThatThrownBy(()->old.priceFor(SeatType.VIP)).isInstanceOf(IllegalStateException.class);assertThat(repository.count()).isEqualTo(1);
 }
 @Test void explicitUpgradeKeepsLegacyIdAndBasePrice(){
  var old=legacy();var changed=schedules.update(old.getId(),form("85000","65000"));assertThat(changed.id()).isEqualTo(old.getId());assertThat(changed.basePrice()).isEqualByComparingTo("75000");assertThat(schedules.getBookableShowtime(old.getId()).vipPrice()).isEqualByComparingTo("65000");
 }
 @Test void unconfiguredLegacyScheduleStillOccupiesItsRoom(){
  legacy();assertThatThrownBy(()->create()).isInstanceOf(ScheduleValidationException.class).hasMessageContaining("trùng");assertThat(repository.count()).isEqualTo(1);
 }
 @Test void legacyZeroBasePriceIsPreservedAndCanStillBeCancelled(){
  var old=legacy();new TransactionTemplate(txManager).executeWithoutResult(tx->repository.findById(old.getId()).orElseThrow().setBasePrice(BigDecimal.ZERO));
  assertThat(schedules.getForAdmin(old.getId()).basePrice()).isEqualByComparingTo("0");
  assertThatThrownBy(()->schedules.getBookableShowtime(old.getId())).isInstanceOf(ScheduleValidationException.class);
  schedules.changeStatus(old.getId(),ShowtimeStatus.CANCELLED);assertThat(schedules.getForAdmin(old.getId()).status()).isEqualTo(ShowtimeStatus.CANCELLED);assertThat(repository.count()).isEqualTo(1);
 }
 @Test void databaseCheckRejectsNonPositiveNewPrices(){
  var s=create();assertThatThrownBy(()->jdbc.update("update showtimes set normal_price=0 where id=?",s.id())).isInstanceOf(DataIntegrityViolationException.class);
  assertThatThrownBy(()->jdbc.update("update showtimes set vip_price=-1 where id=?",s.id())).isInstanceOf(DataIntegrityViolationException.class);
  assertThat(schedules.getForAdmin(s.id()).normalPrice()).isEqualByComparingTo("80000");
 }
 @Test void adminPriceChangeDoesNotAlterHistoricalPriceSnapshot(){
  var s=create();jdbc.update("insert into price_history_fixture(showtime_id,price_at_booking) values(?,?)",s.id(),new BigDecimal("100000"));
  schedules.update(s.id(),form("85000","65000"));assertThat(jdbc.queryForObject("select price_at_booking from price_history_fixture",BigDecimal.class)).isEqualByComparingTo("100000");
  assertThat(jdbc.queryForObject("select showtime_id from price_history_fixture",Long.class)).isEqualTo(s.id());
 }
 @Test void overlapValidationStillAppliesWithDifferentPrices(){
  create();assertThatThrownBy(()->schedules.create(form("70000","50000"))).isInstanceOf(ScheduleValidationException.class).hasMessageContaining("trùng");assertThat(repository.count()).isEqualTo(1);
 }
}
